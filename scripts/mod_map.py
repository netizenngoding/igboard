#!/usr/bin/env python3
"""Map the iBoard modification surface from the decoded smali tree.

Finds every class in the `mk` package, every Gboard class that calls into it,
and the assets/fonts the mod adds. Writes analysis/mod-map.json (machine
readable) and analysis/mod-map.md (tables).

    python3 scripts/mod_map.py            # reads decompiled/apktool
"""

from __future__ import annotations

import json
import os
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(os.environ.get("OUT", ROOT / "decompiled")).resolve()
ANA = Path(os.environ.get("ANA", ROOT / "analysis")).resolve()
MOD_PREFIX = os.environ.get("MOD_PREFIX", "mk")

CALL = re.compile(r"L(" + MOD_PREFIX + r"/[A-Za-z0-9_$]+);->([A-Za-z0-9_$<>]+)")
CLASS_LINE = re.compile(r"^\.class[^\n]*L([^;]+);$", re.MULTILINE)
SUPER_LINE = re.compile(r"^\.super L([^;]+);$", re.MULTILINE)
SOURCE_LINE = re.compile(r'^\.source "(.*)";$', re.MULTILINE)


def dex_dirs() -> list[Path]:
    return sorted([p for p in (OUT / "apktool").glob("smali*") if p.is_dir()],
                  key=lambda p: (len(p.name), p.name))


def read(path: Path) -> str:
    return path.read_text("utf-8", "ignore")


def main() -> int:
    dirs = dex_dirs()
    if not dirs:
        print("no decoded smali tree; run scripts/decompile_apk.sh first", flush=True)
        return 1

    mod_classes: list[dict] = []
    hooks: list[dict] = []
    callers: Counter = Counter()
    per_dex: dict[str, list[str]] = defaultdict(list)
    scanned = 0

    for smali in dirs:
        for path in smali.rglob("*.smali"):
            scanned += 1
            text = read(path)
            cls = CLASS_LINE.search(text)
            if not cls:
                continue
            name = cls.group(1)
            rel = str(path.relative_to(OUT))
            if name.startswith(MOD_PREFIX + "/"):
                mod_classes.append({
                    "class": name.replace("/", "."),
                    "dex": smali.name.replace("smali", "classes") + ".dex"
                    if smali.name != "smali" else "classes.dex",
                    "super": (SUPER_LINE.search(text) or [None, None])[1],
                    "source": (SOURCE_LINE.search(text) or [None, None])[1],
                    "smali": rel,
                    "bytes": path.stat().st_size,
                    "methods": len(re.findall(r"^\.method ", text, re.MULTILINE)),
                })
                per_dex[smali.name].append(name)
                continue
            calls = sorted({f"{c}->{m}" for c, m in CALL.findall(text)})
            if calls:
                hooks.append({"class": name.replace("/", "."), "smali": rel, "calls": calls})
                for call in calls:
                    callers[call] += 1

    mod_classes.sort(key=lambda c: (c["dex"], c["class"]))
    hooks.sort(key=lambda h: h["class"])

    assets = []
    for pattern in ("assets/theme/*", "res/font/*", "assets/*"):
        for path in (OUT / "apktool").glob(pattern):
            if path.is_file() and (MOD_PREFIX in path.name or path.name.startswith("sf_")):
                assets.append({"path": str(path.relative_to(OUT)), "bytes": path.stat().st_size})

    data = {
        "smali_files_scanned": scanned,
        "mod_package": MOD_PREFIX,
        "mod_classes": mod_classes,
        "hook_count": len(hooks),
        "hooks": hooks,
        "mod_assets": assets,
        "classes_per_dex": {k: len(v) for k, v in per_dex.items()},
        "call_frequency": callers.most_common(),
    }
    ANA.mkdir(parents=True, exist_ok=True)
    (ANA / "mod-map.json").write_text(json.dumps(data, indent=2), encoding="utf-8")

    def table(rows, header):
        body = [header, ["---"] * len(header)] + rows
        return "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in body)

    md = [
        "# Modification map",
        "",
        f"`{MOD_PREFIX}/*` is the only non-stock package in the app. "
        f"{len(mod_classes)} mod classes across "
        f"{len({c['dex'] for c in mod_classes})} dex container(s); "
        f"{len(hooks)} stock classes call into them.",
        "",
        "## Mod classes",
        "",
        table([[f"`{c['class']}`", c["dex"], c["methods"], f"`{c['super']}`", c["bytes"]]
               for c in mod_classes],
              ["class", "dex", "methods", "super", "smali bytes"]),
        "",
        "## Hook sites (stock code calling the mod)",
        "",
        table([[f"`{h['class']}`", ", ".join(f"`{c}`" for c in h["calls"])] for h in hooks],
              ["stock class", "calls"]),
        "",
        "## Added assets",
        "",
        table([[f"`{a['path']}`", a["bytes"]] for a in assets], ["asset", "bytes"])
        if assets else "_none_",
        "",
        f"_generated by `scripts/mod_map.py` from {scanned} smali files_",
        "",
    ]
    (ANA / "mod-map.md").write_text("\n".join(md), encoding="utf-8")

    print(f"mod classes: {len(mod_classes)}, hooks: {len(hooks)}, assets: {len(assets)}")
    print(f"wrote {ANA / 'mod-map.json'} and {ANA / 'mod-map.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
